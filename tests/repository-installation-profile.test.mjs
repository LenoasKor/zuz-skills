import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { planInstallation, installPackage } from '../scripts/install-decal-pack.mjs';
import { repositoryRoot } from '../scripts/pack-lib.mjs';
const descriptor = JSON.parse(await readFile(path.join(repositoryRoot, 'packs/decal-pack/pack.source.json')));
execFileSync(process.execPath, [path.join(repositoryRoot, 'scripts/build-decal-pack.mjs'), '--source-revision', 'a'.repeat(40)]);
const original = await readFile(path.join(repositoryRoot, `dist/decal-pack-${descriptor.packVersion}.zuz-pack.json`));
async function fixture(t) {
  const parent = await mkdtemp('/private/tmp/common-installation-profile-');
  t.after(() => rm(parent, { recursive: true, force: true }));
  const root = path.join(parent, 'project'); await mkdir(root);
  const packagePath = path.join(parent, 'pack.json'); await writeFile(packagePath, original);
  const options = { rootValue: root, packagePath, modules: ['zuz-its'], providers: ['acp', 'claude', 'codex', 'gemini'] };
  const plan = await planInstallation(options);
  await installPackage({ ...options, approvedPlanDigest: plan.installationPlanDigest });
  const lockPath = path.join(root, '.decal/decal-pack.lock.json');
  const lock = JSON.parse(await readFile(lockPath));
  const excluded = lock.files.filter(f => /^contracts\/task-work-bug\/v[1-4]\//u.test(f.path));
  lock.repositoryProfile = { id: 'jig.development-task-authoring/v1', preservedPaths: excluded.map(f => f.path), protectedFiles: [] };
  lock.files = lock.files.filter(f => !excluded.includes(f));
  await writeFile(lockPath, JSON.stringify(lock));
  await mkdir(path.join(root, 'contracts/jig-task-authoring/v1'), { recursive: true });
  await writeFile(path.join(root, 'contracts/jig-task-authoring/v1/manifest.json'), 'historical profile');
  await mkdir(path.join(root, 'docs/tasks'), { recursive: true });
  await writeFile(path.join(root, 'docs/tasks/task_284_old.md'), 'historical record');
  await mkdir(path.join(root, 'assets/its-consumer-history'), { recursive: true });
  await writeFile(path.join(root, 'assets/its-consumer-history/snapshot.json'), 'preserve archive');
  return { root, options, lockPath, excluded };
}
test('aligned historical receipt adopts all common contracts and repeat update is current', async t => {
  const { root, options, lockPath, excluded } = await fixture(t);
  const plan = await planInstallation(options);
  assert.equal(plan.status, 'planned'); assert.equal(plan.conflicts.length, 0);
  assert.equal(plan.repositoryProfile, undefined);
  await installPackage({ ...options, approvedPlanDigest: plan.installationPlanDigest });
  const next = JSON.parse(await readFile(lockPath));
  assert.equal(next.repositoryProfile, undefined);
  for (const f of excluded) assert.ok(next.files.some(n => n.path === f.path && n.sha256 === f.sha256), f.path);
  assert.equal((await planInstallation(options)).status, 'current');
  assert.equal(await readFile(path.join(root, 'docs/tasks/task_284_old.md'), 'utf8'), 'historical record');
  assert.equal(await readFile(path.join(root, 'assets/its-consumer-history/snapshot.json'), 'utf8'), 'preserve archive');
  assert.equal(await readFile(path.join(root, 'contracts/jig-task-authoring/v1/manifest.json'), 'utf8'), 'historical profile');
});
test('different excluded contract bytes remain conflicts and are never overwritten', async t => {
  const { root, options } = await fixture(t);
  const file = path.join(root, 'contracts/task-work-bug/v1/README.md');
  await writeFile(file, 'historical incompatible bytes');
  const plan = await planInstallation(options);
  assert.equal(plan.status, 'blocked'); assert.ok(plan.conflicts.includes('contracts/task-work-bug/v1/README.md'));
  await assert.rejects(() => installPackage({ ...options, approvedPlanDigest: plan.installationPlanDigest }));
  assert.equal(await readFile(file, 'utf8'), 'historical incompatible bytes');
});
test('changing an adopted contract after preview invalidates approval', async t => {
  const { root, options, lockPath } = await fixture(t); const before = await readFile(lockPath);
  const plan = await planInstallation(options);
  await writeFile(path.join(root, 'contracts/task-work-bug/v1/README.md'), 'interleaved edit');
  await assert.rejects(() => installPackage({ ...options, approvedPlanDigest: plan.installationPlanDigest }), /approval_plan_digest_mismatch|blocked/u);
  assert.deepEqual(await readFile(lockPath), before);
});
test('receipt-only migration rollback preserves the old receipt and unrelated files', async t => {
  const { root, options, lockPath } = await fixture(t); const before = await readFile(lockPath);
  await writeFile(path.join(root, 'unrelated.txt'), 'user edit');
  const plan = await planInstallation(options);
  await assert.rejects(() => installPackage({ ...options, approvedPlanDigest: plan.installationPlanDigest, testFailAt: 'after_first_write' }));
  assert.deepEqual(await readFile(lockPath), before);
  assert.equal(await readFile(path.join(root, 'unrelated.txt'), 'utf8'), 'user edit');
});
